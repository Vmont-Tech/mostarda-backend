#!/usr/bin/env python3
"""
MOSTARDA — Gerador de Chaves para Ambiente de Teste (Devnet/Testnet)

Gera automaticamente:
  1. Par de chaves Stellar (Testnet) — Keypair.random() + Friendbot funding
  2. Par de chaves Solana (Devnet) — Keypair() + request_airdrop

Saída: .env.dev  (pronto para usar com docker-compose ou dotenv)

Uso:
  python scripts/generate_test_keys.py          # Gera e salva
  python scripts/generate_test_keys.py --show   # Apenas exibe, não salva
  python scripts/generate_test_keys.py --fund   # Gera + funde via Friendbot/Airdrop
"""

import argparse
import os
import sys
from pathlib import Path


# Paths
SCRIPT_DIR = Path(__file__).parent.resolve()
PROJECT_DIR = SCRIPT_DIR.parent
ENV_DEV_PATH = PROJECT_DIR / ".env.dev"

# Stellar Testnet
STELLAR_HORIZON = "https://horizon-testnet.stellar.org"
STELLAR_FRIENDBOT = "https://friendbot.stellar.org"
STELLAR_NETWORK = "Test SDF Network ; September 2015"

# Solana Devnet
SOLANA_RPC = "https://api.devnet.solana.com"
SOLANA_AIRDROP_AMOUNT = 2_000_000_000  # 2 SOL em lamports


def banner(text: str):
    print()
    print("=" * 60)
    print(f"  {text}")
    print("=" * 60)


def generate_stellar_keypair() -> dict:
    """Generate a random Stellar keypair and optionally fund via Friendbot."""
    try:
        from stellar_sdk import Keypair
    except ImportError:
        print("❌ stellar-sdk not installed. Run: pip install stellar-sdk requests")
        sys.exit(1)

    banner("🌐 Gerando chave Stellar Testnet")
    keypair = Keypair.random()
    print(f"  Public Key:  {keypair.public_key}")
    print(f"  Secret Seed: {keypair.secret}")
    print(f"  Horizon:     {STELLAR_HORIZON}")
    print(f"  Network:     {STELLAR_NETWORK}")
    return {
        "public": keypair.public_key,
        "secret": keypair.secret,
    }


def fund_stellar(public_key: str) -> bool:
    """Fund a Stellar Testnet account via Friendbot."""
    import requests
    try:
        print(f"\n  ⏳ Funding Stellar account {public_key[:16]}... via Friendbot...")
        resp = requests.get(
            STELLAR_FRIENDBOT,
            params={"addr": public_key},
            timeout=30,
        )
        if resp.status_code == 200:
            data = resp.json()
            hash_tx = data.get("hash", "unknown")
            print(f"  ✅ Stellar funded! TX hash: {hash_tx[:16]}...")
            return True
        else:
            print(f"  ⚠️ Stellar funding returned HTTP {resp.status_code}: {resp.text[:100]}")
            return False
    except requests.RequestException as e:
        print(f"  ⚠️ Stellar funding error (network may be down): {e}")
        return False


def generate_solana_keypair() -> dict:
    """Generate a random Solana keypair."""
    try:
        from solders.keypair import Keypair
    except ImportError:
        print("❌ solders not installed. Run: pip install solana solders")
        sys.exit(1)

    banner("🌐 Gerando chave Solana Devnet")
    keypair = Keypair()
    pubkey = str(keypair.pubkey())
    secret_bytes = bytes(keypair)
    secret_hex = secret_bytes.hex()

    print(f"  Public Key:  {pubkey}")
    print(f"  Secret Key:  {secret_hex[:32]}... (hex)")
    print(f"  RPC:         {SOLANA_RPC}")
    return {
        "public": pubkey,
        "secret_hex": secret_hex,
    }


async def fund_solana(public_key: str) -> bool:
    """Fund a Solana Devnet account via airdrop."""
    try:
        from solana.rpc.async_api import AsyncClient
        from solders.pubkey import Pubkey
    except ImportError:
        print("  ⚠️ solana-py not installed. Skipping funding.")
        return False

    try:
        pubkey_obj = Pubkey.from_string(public_key)
        async with AsyncClient(SOLANA_RPC) as client:
            print(f"\n  ⏳ Requesting airdrop of {SOLANA_AIRDROP_AMOUNT / 1_000_000_000} SOL to {public_key[:16]}...")
            resp = await client.request_airdrop(pubkey_obj, SOLANA_AIRDROP_AMOUNT)
            tx_sig = resp.value
            print(f"  ⏳ Confirming transaction {str(tx_sig)[:16]}...")
            await client.confirm_transaction(tx_sig, commitment="confirmed")
            balance = await client.get_balance(pubkey_obj)
            sol = balance.value / 1_000_000_000
            print(f"  ✅ Solana funded! Balance: {sol:.2f} SOL")
            return True
    except Exception as e:
        print(f"  ⚠️ Solana funding error: {e}")
        return False


