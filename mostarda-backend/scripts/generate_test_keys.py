async def main():
    parser = argparse.ArgumentParser(description="Generate test keys for Stellar Testnet + Solana Devnet")
    parser.add_argument("--show", action="store_true", help="Only display keys, don't save")
    parser.add_argument("--fund", action="store_true", help="Fund accounts via Friendbot/Airdrop")
    args = parser.parse_args()

    print()
    print("🍅 MOSTARDA — Gerador de Chaves de Teste")
    print("  Stellar Testnet + Solana Devnet")

    # Generate keys
    stellar = generate_stellar_keypair()
    solana = generate_solana_keypair()

    # Funding (optional)
    funded = args.fund
    stellar_funded = False
    solana_funded = False

    if funded:
        banner("💰 Fundindo contas de teste")
        stellar_funded = fund_stellar(stellar["public"])
        import asyncio
        solana_funded = await fund_solana(solana["public"])

    if args.show:
        banner("📋 Chaves geradas (não salvas)")
        print(f"\nStellar:")
        print(f"  STELLAR_DISTRIBUTION_SEED={stellar['secret']}")
        print(f"  (public: {stellar['public']})")
        print(f"\nSolana:")
        print(f"  SOLANA_SECRET={solana['secret_hex']}")
        print(f"  (public: {solana['public']})")
        return

    # Write .env.dev
    banner("📝 Salvando .env.dev")
    write_env(stellar, solana, funded, stellar_funded, solana_funded)

    print()
    print("  🚀 Para iniciar o ambiente:")
    print("    docker compose up -d --build")
    print()
    print("  ℹ️  Para carregar sem Docker:")
    print(f"    cp {ENV_DEV_PATH} .env")
    print("    uvicorn main:app --reload")
    print()


if __name__ == "__main__":
    import asyncio
    asyncio.run(main())
